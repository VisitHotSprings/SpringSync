#!/usr/bin/env python3
"""Write requirements-windows.lock (SPEC v0.9 §11.5: separate lock for the Windows host).

Input: a directory of win_amd64 / cp313 wheels fetched with
    pip download --only-binary=:all: --platform win_amd64 --python-version 3.13 --implementation cp \
        -d wheels -r <pins>
Rules: every package pinned in requirements.lock must have the SAME version, and its wheel's SHA-256 must
already be one of that package's hashes in requirements.lock (so the Windows set is the reviewed Linux set).
Windows-only extras (pywin32, tzdata, colorama) must be given with --extra NAME=SHA256, which the release
engineer copies from pypi.org/pypi/<name>/<ver>/json. One hash per package: the exact wheel shipped.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path


def norm(n: str) -> str:
    return re.sub(r"[-_.]+", "-", n).lower()


def parse_lock(p: Path) -> dict[str, tuple[str, set[str]]]:
    out, cur = {}, None
    for line in p.read_text().splitlines():
        m = re.match(r"^([A-Za-z0-9_.-]+)==([^\s\\]+)", line)
        if m:
            cur = norm(m.group(1))
            out[cur] = (m.group(2), set())
            continue
        h = re.search(r"--hash=sha256:([0-9a-f]{64})", line)
        if h and cur:
            out[cur][1].add(h.group(1))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("wheels", type=Path)
    ap.add_argument("--linux-lock", type=Path, default=Path(__file__).resolve().parents[2] / "requirements.lock")
    ap.add_argument("--extra", action="append", default=[], help="name=sha256 for Windows-only packages")
    ap.add_argument("-o", "--out", type=Path, required=True)
    a = ap.parse_args()
    lin = parse_lock(a.linux_lock)
    extra = {norm(k): v for k, v in (e.split("=", 1) for e in a.extra)}
    rows, errs = [], []
    for whl in sorted(a.wheels.glob("*.whl")):
        name, ver = whl.name.split("-")[:2]
        n = norm(name)
        h = hashlib.sha256(whl.read_bytes()).hexdigest()
        if n in lin:
            lv, hs = lin[n]
            if lv != ver:
                errs.append(f"{n}: {ver} != linux lock {lv}")
            if h not in hs:
                errs.append(f"{n}: {whl.name} hash not in requirements.lock")
            src = "same as requirements.lock"
        elif n in extra:
            if extra[n] != h:
                errs.append(f"{n}: {whl.name} hash {h} != --extra {extra[n]}")
            src = "Windows only; hash cross-checked with pypi.org JSON"
        else:
            errs.append(f"{n}: not in requirements.lock and no --extra hash")
            continue
        rows.append(f"{n}=={ver} \\\n    --hash=sha256:{h}\n    # {whl.name} ({src})\n")
    missing = set(lin) - {norm(w.name.split('-')[0]) for w in a.wheels.glob('*.whl')}
    if missing:
        errs.append("missing wheels: " + ", ".join(sorted(missing)))
    if errs:
        print("\n".join(errs), file=sys.stderr)
        return 1
    a.out.write_text("# requirements-windows.lock: Windows 11 host, CPython 3.13 win_amd64 (SPEC v0.9 §11.5).\n"
                     "# Generated by deploy/windows/make-windows-lock.py; do not edit by hand.\n"
                     "# install.ps1 runs pip with --require-hashes --no-index --only-binary=:all: against the\n"
                     "# wheels shipped in the release zip, so nothing is fetched at install time.\n"
                     + "".join(rows))
    print(f"wrote {a.out} ({len(rows)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
