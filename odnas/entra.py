"""Microsoft Entra (SPEC §4.1). The MSAL dependency is behind EntraClient so
tests (and the lab) can substitute a fake. Nothing here runs at import time and
no network call is made until a method is invoked.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Protocol

from odnas.config import CRED_CERT, DELEGATED_SCOPES, Config

REAUTH_CODES = {"AADSTS700082", "AADSTS50173", "AADSTS50076", "AADSTS50078"}
CA_CODES = {"AADSTS53000", "AADSTS53003"}
_CODE_RE = re.compile(r"AADSTS(\d{5,6})")

AUTH_OK, AUTH_REAUTH, AUTH_CA, AUTH_TRANSIENT = "ok", "needs_reauth", "blocked_by_ca", "transient"


def classify_auth_error(error: str | None, description: str | None = "", codes: list[int] | None = None) -> str:
    """Map a token-endpoint error (or free text from an rclone log) to an action (SPEC §4.1).

    CA wins over re-auth: a CA block can arrive as invalid_grant + AADSTS53003, and asking the
    user to sign in again won't help; the admin must look at the policy.
    """
    text = f"{error or ''} {description or ''}"
    found = {f"AADSTS{m}" for m in _CODE_RE.findall(text)} | {f"AADSTS{c}" for c in (codes or [])}
    if found & CA_CODES:
        return AUTH_CA
    if found & REAUTH_CODES or re.search(r"\b(invalid_grant|interaction_required)\b", text):
        return AUTH_REAUTH
    if error or found:
        return AUTH_TRANSIENT
    return AUTH_OK


@dataclass
class TokenResult:
    access_token: str = field(default="", repr=False)
    refresh_token: str = field(default="", repr=False)
    expires_in: int = 0
    id_claims: dict[str, Any] = field(default_factory=dict)
    error: str = ""
    error_description: str = ""
    error_codes: list[int] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.error and bool(self.access_token)

    @property
    def classification(self) -> str:
        return AUTH_OK if self.ok else classify_auth_error(self.error, self.error_description, self.error_codes)


class EntraClient(Protocol):
    def begin_auth(self, redirect_uri: str) -> dict: ...
    def complete_auth(self, flow: dict, query: dict[str, str]) -> TokenResult: ...
    def refresh(self, refresh_token: str) -> TokenResult: ...
    def get_drive(self, access_token: str) -> dict: ...


def _from_msal(result: dict, cache_rt: str = "") -> TokenResult:
    if "error" in result:
        return TokenResult(error=result.get("error", ""), error_description=result.get("error_description", ""),
                           error_codes=list(result.get("error_codes") or []))
    return TokenResult(access_token=result.get("access_token", ""),
                       refresh_token=result.get("refresh_token") or cache_rt,
                       expires_in=int(result.get("expires_in") or 0),
                       id_claims=result.get("id_token_claims") or {})


def certificate_expiry(cert_pem: bytes) -> datetime:
    from cryptography import x509
    return x509.load_pem_x509_certificate(cert_pem).not_valid_after_utc


def certificate_thumbprint(cert_pem: bytes) -> str:
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes
    return x509.load_pem_x509_certificate(cert_pem).fingerprint(hashes.SHA1()).hex().upper()  # noqa: S303 (Entra uses SHA-1 thumbprints)


class MsalEntraClient:
    """Confidential client, single tenant. Certificate credential preferred (SPEC §4.1)."""

    def __init__(self, cfg: Config):
        self.cfg = cfg
        self._app = None

    def _credential(self) -> Any:
        if self.cfg.credential_type == CRED_CERT:
            cert = open(self.cfg.cert_path, "rb").read()
            return {"private_key": self.cfg.read_secret("entra-app.key").decode(),
                    "thumbprint": certificate_thumbprint(cert), "public_certificate": cert.decode()}
        return self.cfg.read_secret("entra-client-secret").decode().strip()

    def _msal(self, cache=None):
        import msal  # imported lazily: tests never need it
        return msal.ConfidentialClientApplication(self.cfg.client_id, authority=self.cfg.authority,
                                                  client_credential=self._credential(), token_cache=cache)

    @staticmethod
    def _rt_from_cache(cache) -> str:
        data = json.loads(cache.serialize() or "{}")
        rts = list((data.get("RefreshToken") or {}).values())
        return rts[0]["secret"] if rts else ""

    def begin_auth(self, redirect_uri: str) -> dict:
        # PKCE + state + nonce are generated by MSAL's auth-code-flow helper.
        return self._msal().initiate_auth_code_flow(list(DELEGATED_SCOPES), redirect_uri=redirect_uri,
                                                    prompt="select_account")

    def complete_auth(self, flow: dict, query: dict[str, str]) -> TokenResult:
        import msal
        cache = msal.SerializableTokenCache()
        res = self._msal(cache).acquire_token_by_auth_code_flow(flow, query)
        return _from_msal(res, self._rt_from_cache(cache))

    def refresh(self, refresh_token: str) -> TokenResult:
        import msal
        cache = msal.SerializableTokenCache()
        res = self._msal(cache).acquire_token_by_refresh_token(refresh_token, scopes=["Files.ReadWrite"])
        return _from_msal(res, self._rt_from_cache(cache))

    def get_drive(self, access_token: str) -> dict:
        import httpx
        r = httpx.get("https://graph.microsoft.com/v1.0/me/drive", timeout=30,
                      headers={"Authorization": f"Bearer {access_token}", "User-Agent": self.cfg.user_agent})
        r.raise_for_status()
        j = r.json()
        return {"id": j["id"], "driveType": j.get("driveType", "business")}


def now_utc() -> datetime:
    return datetime.now(timezone.utc)
